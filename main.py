        # __init__: 객체가 생성될 때 자동으로 실행되는 초기화 메서드
        # self: 이 객체 자신을 가리키는 참조
        self.question = question  # 문제 텍스트 (str)
        self.choices = choices    # 선택지 리스트 (list, 4개)
        self.answer = answer      # 정답 번호 (int, 1~4)


